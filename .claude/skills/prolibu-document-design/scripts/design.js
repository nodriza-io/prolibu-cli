function contactName(c) {
  if (!c || typeof c !== 'object') return null;
  return [c.firstName, c.lastName].filter(Boolean).join(' ') || c.email || null;
}

function isExpired(date, now = Date.now()) {
  return Boolean(date) && new Date(date).getTime() < now;
}

function presentationRow(p) {
  const tr = p.tracking || {};
  return {
    id: p._id,
    code: p.presentationCode,
    title: p.title,
    contact: p.contact && typeof p.contact === 'object' ? { id: p.contact._id, name: contactName(p.contact), email: p.contact.email } : p.contact,
    layout: p.layout && typeof p.layout === 'object' ? { id: p.layout._id, name: p.layout.contentTemplateName } : p.layout,
    views: tr.totalViews || 0,
    lastSeenAt: tr.lastSeenAt || null,
    expirationDate: p.expirationDate || null,
    expired: isExpired(p.expirationDate),
    createdAt: p.createdAt,
  };
}

const PRESENTATION_POPULATE = JSON.stringify([
  { path: 'contact', select: 'firstName lastName email' },
  { path: 'layout', select: 'contentTemplateName' },
  { path: 'assignee', select: 'firstName lastName email' },
]);

async function resolveContact(client, ref) {
  if (ID_RE.test(ref)) return ref;
  const res = await list(client, 'contact', { limit: 2, select: '_id email', xquery: { email: { $regex: `(?i)^${escapeRegex(String(ref).trim())}$` } } });
  if (!res.data.length) throw new Blocked(`No contact with the e-mail ${ref}.`);
  return res.data[0]._id;
}

async function cmdPresentations(client, rest, flags) {
  const xquery = {};
  if (flags.contact) xquery.contact = await resolveContact(client, flags.contact);
  if (rest[0]) xquery.title = { $regex: `(?i)${escapeRegex(rest[0])}` };
  const res = await list(client, 'presentation', {
    limit: 50,
    sort: '-createdAt',
    select: 'title presentationCode contact layout expirationDate tracking.totalViews tracking.lastSeenAt createdAt',
    populatePath: PRESENTATION_POPULATE,
    ...(Object.keys(xquery).length ? { xquery } : {}),
  });
  return { count: res.count, shown: res.data.length, presentations: res.data.map(presentationRow) };
}

