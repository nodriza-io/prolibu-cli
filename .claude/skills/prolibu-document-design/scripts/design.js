// ── plans ────────────────────────────────────────────────────────────────────────────────────────

function readPlan(arg, rootDir) {
  let text = String(arg || '');
  if (!text.trim().startsWith('{')) {
    if (!text) throw new UsageError('Missing the plan (inline JSON in single quotes, or a temp file path).');
    assertDataFileAllowed(text, rootDir);
    text = fs.readFileSync(text, 'utf8');
  }
  let plan;
  try {
    plan = JSON.parse(text);
  } catch {
    throw new UsageError('The plan is not valid JSON.');
  }
  if (!plan || typeof plan !== 'object' || Array.isArray(plan)) throw new UsageError('The plan must be a JSON object.');
  if (!['duplicate', 'edit', 'default', 'create', 'font', 'view'].includes(plan.kind)) {
    throw new UsageError('"kind" must be duplicate, edit, default, create, font or view.');
  }
  return plan;
}

function needString(value, name, max = 120) {
  if (typeof value !== 'string' || !value.trim()) throw new UsageError(`"${name}" must be a non-empty text.`);
  if (value.length > max) throw new UsageError(`"${name}" is longer than ${max} characters.`);
  return value.trim();
}

async function nameTaken(client, name) {
  const res = await list(client, 'contenttemplate', { limit: 5, select: 'contentTemplateName', xquery: { contentTemplateName: name } });
  return res.data.find((t) => t.contentTemplateName === name) || null;
}

async function checkFonts(client, codes, blockers) {
  if (!codes.length) return;
  const fonts = await loadFonts(client);
  const known = new Set(fonts.map((f) => f.fontCode));
  // Older templates list File ids instead of font codes; the editor still reads them.
  for (const c of codes) if (!known.has(c) && !ID_RE.test(c)) blockers.push(`There is no font with the code "${c}" (run fonts).`);
}

async function planDuplicate(client, plan) {
  if (!plan.from) throw new UsageError('A duplicate plan needs "from" (template id or code).');
  const name = needString(plan.name, 'name');
  const src = await loadTemplate(client, String(plan.from));
  const body = { contentTemplateName: name };
  for (const f of COPY_FIELDS) if (src[f] !== undefined && src[f] !== null) body[f] = src[f];
  if (plan.language !== undefined) {
    if (!LANGS_RE.test(String(plan.language))) throw new UsageError('"language" must be a two-letter code such as es or en.');
    body.taxonomy = { ...(src.taxonomy || {}), language: plan.language };
  }
  const warnings = [];
  const blockers = [];
  if (await nameTaken(client, name)) blockers.push(`A template named "${name}" already exists: choose another name (it may be a duplicate made earlier).`);
  if (!src.html || !String(src.html).trim()) blockers.push('The source template has no design yet (empty html): there is nothing to copy.');
  if (Array.isArray(src.assets) && src.assets.length) {
    warnings.push(`The copy points to the same ${src.assets.length} image file(s) as the original. Replacing an image in the editor of one does not change the other, but deleting the file breaks both. For fully independent images use Clone in the app's templates list.`);
  }
  if (src.retargeting && src.retargeting.metaPixelId) warnings.push('The Meta pixel is not copied: set the right pixel for the copy with an edit plan if it needs one.');
  if (src.defaultLayout && src.defaultLayout.origin) warnings.push('The original is a default layout; the copy is not (only one default per scope).');
  if (src.library && src.library.publish) warnings.push('The original is published in the public library; the copy is not.');
  return {
    body,
    source: { id: src._id, name: src.contentTemplateName, type: src.templateType, updatedAt: src.updatedAt },
    changes: [{ action: 'create', type: src.templateType, name, copiedFrom: src.contentTemplateName, pages: Array.isArray(src.pages) ? src.pages.length : 0 }],
    warnings,
    blockers,
    version: hashOf({ plan, from: src.updatedAt }),
    afterApply: 'Open the copy in the app\'s visual editor to change its design; the original and every proposal that uses it stay as they are.',
  };
}

function editBody(t, set, warnings) {
  const body = {};
  const changes = [];
  const push = (field, before, after, payload) => {
    if (JSON.stringify(before ?? null) === JSON.stringify(after ?? null)) return;
    Object.assign(body, payload);
    changes.push({ field, before: before ?? null, after: after ?? null });
  };
  for (const [k, v] of Object.entries(set)) {
    if (REFUSED[k]) throw new UsageError(`"${k}" ${REFUSED[k]}.`);
    if (!EDITABLE.includes(k)) throw new UsageError(`"${k}" cannot be edited here. Editable: ${EDITABLE.join(', ')}.`);
    if (k === 'name') push('name', t.contentTemplateName, needString(v, 'name'), { contentTemplateName: v.trim() });
    if (k === 'active') {
      if (typeof v !== 'boolean') throw new UsageError('"active" must be true or false.');
      if (!v && t.defaultLayout && t.defaultLayout.origin) warnings.push('This template is a default layout: switching it off does not stop new proposals from using it.');
      push('active', t.active !== false, v, { active: v });
    }
    if (k === 'language') {
      if (!LANGS_RE.test(String(v))) throw new UsageError('"language" must be a two-letter code such as es or en.');
      push('language', t.taxonomy && t.taxonomy.language, v, { taxonomy: { ...(t.taxonomy || {}), language: v } });
    }
    if (k === 'defaultFont' || k === 'secondaryFont') push(k, t[k], needString(v, k), { [k]: v.trim() });
    if (k === 'embeddedFonts') {
      if (!Array.isArray(v) || v.some((c) => typeof c !== 'string' || !c)) throw new UsageError('"embeddedFonts" must be a list of font codes.');
      push(k, t[k] || [], v, { embeddedFonts: v });
    }
    if (k === 'metaPixelId') {
      if (t.templateType !== 'layout') throw new UsageError('Only layout templates have a Meta pixel.');
      if (v !== null && !PIXEL_RE.test(String(v))) throw new UsageError('"metaPixelId" must be 5 to 20 digits, or null to remove it.');
      const after = v === null ? null : String(v);
      push(k, t.retargeting && t.retargeting.metaPixelId, after, { retargeting: { ...(t.retargeting || {}), metaPixelId: after === null ? '' : after } });
      if (after) warnings.push('The pixel fires on every public view of every proposal that uses this layout, including ones already sent. The client\'s privacy notice must cover it.');
    }
  }
  return { body, changes };
}

async function planEdit(client, plan) {
  if (!plan.id) throw new UsageError('An edit plan needs "id" (template id or code).');
  if (!plan.set || typeof plan.set !== 'object' || !Object.keys(plan.set).length) throw new UsageError('The plan changes nothing: add "set".');
  const t = await loadTemplate(client, String(plan.id));
  const warnings = [];
  const blockers = [];
  const { body, changes } = editBody(t, plan.set, warnings);
  const fontCodes = [plan.set.defaultFont, plan.set.secondaryFont, ...(plan.set.embeddedFonts || [])].filter((c) => typeof c === 'string' && c);
  await checkFonts(client, fontCodes, blockers);
  if (plan.set.name && plan.set.name.trim() !== t.contentTemplateName && await nameTaken(client, plan.set.name.trim())) {
    blockers.push(`A template named "${plan.set.name.trim()}" already exists.`);
  }
  const usage = await templateUsage(client, t);
  const live = changes.some((c) => ['language', 'defaultFont', 'secondaryFont', 'embeddedFonts', 'metaPixelId'].includes(c.field));
  const inUse = Object.values(usage.uses).some((u) => u.count === null || u.count > 0);
  if (live && inUse) {
    warnings.push('These changes reach every proposal or presentation listed under uses, at once, including ones already sent. Safer: duplicate the template and change the copy.');
  }
  return {
    id: t._id, name: t.contentTemplateName, type: t.templateType, body, changes, uses: usage.uses, reach: usage.reach,
    warnings, blockers, version: t.updatedAt, unchanged: !changes.length,
  };
}

async function planDefault(client, plan) {
  if (!plan.id) throw new UsageError('A default plan needs "id" (layout id or code).');
  const t = await loadTemplate(client, String(plan.id));
  const blockers = [];
  const warnings = [];
  if (t.templateType !== 'layout') throw new UsageError('Only layout templates can be a default layout.');
  let defaultLayout = null;
  if (plan.origin !== null) {
    if (!ORIGINS.includes(plan.origin)) throw new UsageError(`"origin" must be one of ${ORIGINS.join(', ')}, or null to stop being a default.`);
    defaultLayout = { origin: plan.origin };
    if (plan.origin === 'User Company') {
      if (!ID_RE.test(String(plan.company))) throw new UsageError('"User Company" needs "company" (company id).');
      defaultLayout.company = plan.company;
    }
    if (plan.origin === 'User Primary Workspace') {
      if (!ID_RE.test(String(plan.workspace))) throw new UsageError('"User Primary Workspace" needs "workspace" (workspace id).');
      defaultLayout.primaryWorkspace = plan.workspace;
    }
    const scope = { 'defaultLayout.origin': plan.origin };
    if (defaultLayout.company) scope['defaultLayout.company'] = defaultLayout.company;
    if (defaultLayout.primaryWorkspace) scope['defaultLayout.primaryWorkspace'] = defaultLayout.primaryWorkspace;
    const holders = (await list(client, 'contenttemplate', { limit: 5, select: 'contentTemplateName defaultLayout', xquery: scope })).data
      .filter((h) => String(h._id) !== String(t._id));
    if (holders.length) {
      blockers.push(`"${holders[0].contentTemplateName}" (${holders[0]._id}) is already the default for this scope: the server allows only one. Preview {"kind":"default","id":"${holders[0]._id}","origin":null} first, with its own yes.`);
    }
    warnings.push('From now on, new proposals of the users this covers start with this layout (unless a product brings its own). Existing proposals keep theirs.');
  } else if (!(t.defaultLayout && t.defaultLayout.origin)) {
    return { id: t._id, name: t.contentTemplateName, body: {}, changes: [], warnings, blockers, version: t.updatedAt, unchanged: true };
  } else {
    warnings.push('After this, users covered by it get the next default in line (their workspace, their company, then the global one), or none.');
  }
  return {
    id: t._id,
    name: t.contentTemplateName,
    body: { defaultLayout: defaultLayout || { origin: null } },
    changes: [{ field: 'defaultLayout', before: t.defaultLayout && t.defaultLayout.origin ? t.defaultLayout : null, after: defaultLayout }],
    warnings,
    blockers,
    version: t.updatedAt,
  };
}

async function planCreate(client, plan) {
  const name = needString(plan.name, 'name');
  const type = plan.templateType || 'content';
  if (!TYPES.includes(type) || type === 'customView') throw new UsageError('"templateType" must be layout, content, snippet or certificate.');
  if (plan.html !== undefined || plan.pages !== undefined) throw new UsageError(`"html"/"pages" ${REFUSED.html}. Create the empty template and fill it in the editor.`);
  const body = { contentTemplateName: name, templateType: type };
  if (plan.language !== undefined) {
    if (!LANGS_RE.test(String(plan.language))) throw new UsageError('"language" must be a two-letter code such as es or en.');
    body.taxonomy = { language: plan.language };
  }
  const blockers = [];
  if (await nameTaken(client, name)) blockers.push(`A template named "${name}" already exists.`);
  return {
    body,
    changes: [{ action: 'create', type, name }],
    warnings: ['The template is created empty: its design is made in the app\'s visual editor. Until then it renders a blank document; do not attach it to products or proposals before it has a design.'],
    blockers,
    version: hashOf({ plan }),
  };
}

function readFontFile(file, rootDir) {
  const resolved = path.resolve(String(file || ''));
  if (!file) throw new UsageError('A font plan needs "file" (path to a .ttf, .otf, .woff or .woff2 file).');
  if (/^profile.*\.json$/i.test(path.basename(resolved)) || resolved.startsWith(path.join(rootDir, 'accounts') + path.sep)) {
    throw new UsageError('Refusing to read that file: profile files and anything under accounts/ are never uploaded.');
  }
  const ext = path.extname(resolved).toLowerCase();
  if (!FONT_EXT[ext]) throw new UsageError('Only .ttf, .otf, .woff and .woff2 font files are accepted.');
  let stat;
  try {
    stat = fs.statSync(resolved);
  } catch {
    throw new UsageError(`Cannot read ${file}.`);
  }
  if (!stat.isFile()) throw new UsageError(`${file} is not a file.`);
  if (stat.size > MAX_FONT_BYTES) throw new UsageError(`The file is larger than ${MAX_FONT_BYTES / 1024 / 1024} MB.`);
  const buf = fs.readFileSync(resolved);
  const magic = buf.subarray(0, 4).toString('hex');
  if (!FONT_EXT[ext].includes(magic)) throw new UsageError(`The file content is not a ${ext.slice(1)} font (its first bytes do not match). The server would accept it anyway, so it is refused here.`);
  return { buf, ext, name: path.basename(resolved), sha256: crypto.createHash('sha256').update(buf).digest('hex') };
}

async function planFont(client, plan, ctx) {
  const name = needString(plan.name, 'name', 80);
  const file = readFontFile(plan.file, ctx.rootDir);
  const blockers = [];
  const fonts = await loadFonts(client);
  if (fonts.some((f) => f.fontName === name)) blockers.push(`A font named "${name}" already exists (names are unique and cannot be changed later).`);
  return {
    body: { fontName: name },
    file: { name: file.name, KB: Math.round(file.buf.length / 1024), sha256: file.sha256 },
    changes: [{ action: 'upload font', name, file: file.name }],
    warnings: [
      'The font name cannot be changed after it is created, and only an admin can delete a font in the app.',
      'Every user of the account can use it in the editors. To use it in a template, give its code to an edit plan (defaultFont / embeddedFonts) or pick it in the editor.',
      'Check that the font licence allows embedding it in documents sent to clients.',
    ],
    blockers,
    version: hashOf({ name, sha: file.sha256 }),
    _file: file,
  };
}

async function resolveNames(client, object, nameField, values, blockers) {
  if (values === undefined) return undefined;
  if (!Array.isArray(values)) throw new UsageError(`"${object}" filters must be a list of names or ids.`);
  if (!values.length) return [];
  const res = await list(client, object, { limit: 200, select: nameField });
  const ids = [];
  for (const v of values) {
    const hit = res.data.find((r) => String(r._id) === String(v) || String(r[nameField]).toLowerCase() === String(v).toLowerCase());
    if (hit) ids.push(String(hit._id));
    else blockers.push(`No ${object} named "${v}".`);
  }
  return ids;
}

async function planView(client, plan) {
  const display = plan.display || {};
  if (typeof display !== 'object' || Array.isArray(display)) throw new UsageError('"display" must be an object.');
  for (const k of Object.keys(display)) {
    if (![...VIEW_FLAGS, 'productGroups', 'productFamilies'].includes(k)) throw new UsageError(`"display.${k}" is not a view setting. Use ${VIEW_FLAGS.join(', ')}, productGroups, productFamilies.`);
    if (VIEW_FLAGS.includes(k) && typeof display[k] !== 'boolean') throw new UsageError(`"display.${k}" must be true or false.`);
  }
  const blockers = [];
  const warnings = [];
  const groups = await resolveNames(client, 'productgroup', 'productGroupName', display.productGroups, blockers);
  const families = await resolveNames(client, 'productfamily', 'productFamilyName', display.productFamilies, blockers);
  let current = null;
  if (plan.id) {
    if (!(ID_RE.test(plan.id) || CODE_RE.test(plan.id))) throw new UsageError('"id" must be a view id or code.');
    current = await call(client, 'GET', `/v2/customview/${encodeURIComponent(plan.id)}`);
  }
  const base = current ? { ...VIEW_DEFAULTS, ...(current.display || {}) } : { ...VIEW_DEFAULTS };
  const next = { ...base };
  for (const k of VIEW_FLAGS) if (display[k] !== undefined) next[k] = display[k];
  if (groups !== undefined) next.productGroups = groups;
  if (families !== undefined) next.productFamilies = families;
  if (next.internalNotes) {
    warnings.push('Internal notes would be visible to whoever opens a link shared with this view. Set "internalNotes": false unless the client should read them.');
  }
  const body = { display: next };
  if (!current) body.customViewName = needString(plan.name, 'name');
  else if (plan.name !== undefined) body.customViewName = needString(plan.name, 'name');
  const changes = [];
  for (const k of [...VIEW_FLAGS, 'productGroups', 'productFamilies']) {
    const before = current ? (current.display || {})[k] : undefined;
    if (JSON.stringify(before) !== JSON.stringify(next[k])) changes.push({ field: k, before: before === undefined ? null : before, after: next[k] === undefined ? null : next[k] });
  }
  if (current && body.customViewName && body.customViewName !== current.customViewName) changes.push({ field: 'name', before: current.customViewName, after: body.customViewName });
  warnings.push('A view only changes what the link shows: whoever has the link can edit its address and see the whole proposal, internal notes included. It is not a way to keep data from the client.');
  return {
    id: current ? current._id : undefined,
    action: current ? 'update' : 'create',
    body,
    changes,
    warnings,
    blockers,
    version: current ? current.updatedAt : hashOf({ plan }),
    afterApply: 'To use it: on the deal, Share → Custom view, pick this preset and generate the link in the app.',
  };
}

async function buildPlan(client, plan, ctx) {
  if (plan.kind === 'duplicate') return planDuplicate(client, plan);
  if (plan.kind === 'edit') return planEdit(client, plan);
  if (plan.kind === 'default') return planDefault(client, plan);
  if (plan.kind === 'create') return planCreate(client, plan);
  if (plan.kind === 'font') return planFont(client, plan, ctx);
  return planView(client, plan);
}

function publicPlan(built) {
  const { _file, body, ...rest } = built;
  const shown = { ...body };
  if (shown.pages) shown.pages = `(${shown.pages.length} page(s) copied)`;
  if (shown.html) shown.html = `(${String(shown.html).length} characters copied)`;
  for (const k of ['codes', 'meta', 'assets']) if (shown[k] !== undefined) shown[k] = '(copied)';
  return { ...rest, send: shown };
}

async function cmdPreview(client, rest, flags, ctx) {
  const plan = readPlan(rest[0], ctx.rootDir);
  const built = await buildPlan(client, plan, ctx);
  const out = publicPlan(built);
  out.nextStep = built.blockers.length
    ? 'Blocked: explain each blocker to the user in plain words. Do not apply.'
    : built.unchanged
      ? 'Nothing would change. Tell the user.'
      : `${STOP}Only after the user answers with an explicit yes in a later message, run apply with the same plan and --version ${built.version} --confirmed.`;
  return out;
}

async function readBack(client, object, id) {
  return call(client, 'GET', `/v2/${object}/${id}`);
}

async function cmdApply(client, rest, flags, ctx) {
  if (!flags.version) throw new UsageError('Missing --version. Run preview first and pass its version.');
  if (!flags.confirmed) throw new UsageError('Refusing to write without --confirmed. Show the preview and wait for a yes.');
  const plan = readPlan(rest[0], ctx.rootDir);
  const built = await buildPlan(client, plan, ctx);
  if (built.version !== flags.version) throw new Blocked('Something changed since the preview (or the plan is different). Preview again and show the user the new result. Nothing was written.');
  if (built.blockers.length) throw new Blocked(`${built.blockers.join(' ')} Nothing was written.`);
  if (built.unchanged) return { saved: true, unchanged: true, problems: [] };
  const problems = [];

  if (plan.kind === 'duplicate' || plan.kind === 'create') {
    const created = await call(client, 'POST', '/v2/contenttemplate', { data: built.body, confirmed: true });
    const after = await readBack(client, 'contenttemplate', created._id);
    if (after.contentTemplateName !== built.body.contentTemplateName) problems.push('The name did not save as sent.');
    if (after.templateType !== built.body.templateType) problems.push('The type did not save as sent.');
    if (built.body.html && String(after.html || '').length !== String(built.body.html).length) problems.push('The copied design (html) did not save whole.');
    if (built.body.pages && (after.pages || []).length !== built.body.pages.length) problems.push('The copied pages did not save whole.');
    return { saved: !problems.length, template: templateSummary(after), previewPath: `/ui/spa/view/contenttemplate/${after._id}`, afterApply: built.afterApply, problems };
  }

  if (plan.kind === 'edit' || plan.kind === 'default') {
    await call(client, 'PATCH', `/v2/contenttemplate/${built.id}`, { data: built.body, confirmed: true });
    const after = await readBack(client, 'contenttemplate', built.id);
    const summary = templateSummary(after);
    for (const c of built.changes) {
      const now = {
        name: summary.name, active: summary.active, language: summary.language, defaultFont: summary.defaultFont,
        secondaryFont: summary.secondaryFont, embeddedFonts: summary.embeddedFonts, metaPixelId: summary.metaPixelId,
        defaultLayout: summary.defaultLayout ? { origin: summary.defaultLayout.origin, ...(summary.defaultLayout.company ? { company: String(summary.defaultLayout.company) } : {}), ...(summary.defaultLayout.primaryWorkspace ? { primaryWorkspace: String(summary.defaultLayout.primaryWorkspace) } : {}) } : null,
      }[c.field];
      if (JSON.stringify(now ?? null) !== JSON.stringify(c.after ?? null)) problems.push(`${c.field} did not save as sent.`);
    }
    return { saved: !problems.length, template: summary, changes: built.changes, problems };
  }

  if (plan.kind === 'font') {
    const file = built._file;
    const form = new FormData();
    form.append('fontName', built.body.fontName);
    form.append('fontFile', new Blob([file.buf], { type: 'application/octet-stream' }), file.name);
    const uploader = createClient({
      domain: client.domain,
      rootDir: ctx.rootDir,
      profile: flags.profile,
      fetchImpl: (url, init) => ctx.apiFetch(url, { ...init, body: form }),
      stderr: ctx.stderr,
      timeoutMs: UPLOAD_TIMEOUT_MS,
    });
    const created = await call(uploader, 'POST', '/v2/font', { confirmed: true });
    const after = await call(client, 'GET', `/v2/font/${created._id}?${qs({ populate: 'fontFile' })}`);
    const stored = after.fontFile && typeof after.fontFile === 'object' ? after.fontFile : null;
    if (after.fontName !== built.body.fontName) problems.push('The font name did not save as sent.');
    if (!stored) problems.push('The font has no file attached.');
    return {
      saved: !problems.length,
      font: { id: after._id, code: after.fontCode, name: after.fontName, file: stored ? { size: stored.size, url: stored.url } : null },
      afterApply: `To use it in a template: an edit plan with "defaultFont": "${after.fontCode}" (or embeddedFonts), or pick it in the editor.`,
      problems,
    };
  }

  // view
  const saved = built.action === 'create'
    ? await call(client, 'POST', '/v2/customview', { data: built.body, confirmed: true })
    : await call(client, 'PATCH', `/v2/customview/${built.id}`, { data: built.body, confirmed: true });
  const after = await readBack(client, 'customview', saved._id || built.id);
  for (const k of VIEW_FLAGS) {
    if ((after.display || {})[k] !== built.body.display[k]) problems.push(`display.${k} did not save as sent.`);
  }
  for (const k of ['productGroups', 'productFamilies']) {
    const got = ((after.display || {})[k] || []).map(idOf);
    if (JSON.stringify(got) !== JSON.stringify(built.body.display[k] || [])) problems.push(`display.${k} did not save as sent.`);
  }
  return { saved: !problems.length, view: { id: after._id, code: after.customViewCode, name: after.customViewName, display: after.display }, afterApply: built.afterApply, problems };
}

