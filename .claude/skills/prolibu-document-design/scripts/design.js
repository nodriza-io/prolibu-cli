// ── API helpers ──────────────────────────────────────────────────────────────────────────────────

async function call(client, method, reqPath, opts) {
  const res = await client.request(method, reqPath, opts);
  if (!res.ok) {
    const body = res.body && typeof res.body === 'object' ? res.body : { error: res.body };
    const msg = typeof body.error === 'string' ? body.error : body.message || JSON.stringify(body.error || 'no message');
    const err = new Error(`${method} ${reqPath.split('?')[0]} answered ${res.status}: ${msg}`);
    err.status = res.status;
    throw err;
  }
  return res.body;
}

function qs(params) {
  const sp = new URLSearchParams();
  for (const [k, v] of Object.entries(params)) {
    if (v === undefined || v === null) continue;
    sp.set(k, typeof v === 'object' ? JSON.stringify(v) : String(v));
  }
  return sp.toString();
}

function escapeRegex(text) {
  return String(text).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

async function list(client, object, params) {
  const body = await call(client, 'GET', `/v2/${object}?${qs(params)}`);
  return { data: Array.isArray(body && body.data) ? body.data : [], count: body && body.pagination ? body.pagination.count : null, query: body && body.query };
}

// A filter the server does not know is dropped silently and the list returns every record.
// Count with a filter only when the server echoes it back; otherwise say it is unknown.
async function countWhere(client, object, xquery, select) {
  try {
    const res = await list(client, object, { limit: SAMPLE, select, xquery, sort: '-updatedAt' });
    const kept = res.query && Object.keys(xquery).every((k) => k in res.query);
    if (!kept) return { count: null, note: 'The server ignored this filter; the number of uses is unknown.' };
    return { count: res.count, sample: res.data };
  } catch (err) {
    if (err.status === 403) return { count: null, note: 'This key cannot read these records (403).' };
    throw err;
  }
}

function hashOf(value) {
  return crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex').slice(0, 16);
}

function idOf(ref) {
  if (!ref) return null;
  return String(typeof ref === 'object' ? ref._id || '' : ref) || null;
}

// ── content templates ────────────────────────────────────────────────────────────────────────────

const TEMPLATE_LIST_SELECT = 'contentTemplateName contentTemplateCode templateType taxonomy.language active defaultLayout updatedAt';

function templateRow(t) {
  return {
    id: t._id,
    code: t.contentTemplateCode,
    name: t.contentTemplateName,
    type: t.templateType,
    language: t.taxonomy && t.taxonomy.language,
    active: t.active !== false,
    defaultFor: t.defaultLayout && t.defaultLayout.origin ? t.defaultLayout.origin : undefined,
    updatedAt: t.updatedAt,
  };
}

async function loadTemplate(client, ref) {
  const text = typeof ref === 'string' ? ref.trim() : '';
  if (!text || text.length > 200) throw new UsageError('Give a template id (24 hex characters), its code or its exact name.');
  if (ID_RE.test(text) || CODE_RE.test(text)) {
    try {
      return await call(client, 'GET', `/v2/contenttemplate/${encodeURIComponent(text)}`);
    } catch (err) {
      if (err.status !== 404) throw err;
    }
  }
  // Not an id or code: look it up by its exact name (letter case ignored).
  const res = await list(client, 'contenttemplate', {
    limit: 5, select: 'contentTemplateName templateType', xquery: { contentTemplateName: { $regex: `(?i)^${escapeRegex(text)}$` } },
  });
  if (!res.data.length) throw new Blocked(`There is no template "${text}" that this key can see (run templates to search by part of the name).`);
  if (res.data.length > 1) {
    throw new Blocked(`Several templates are named "${text}": ${res.data.map((t) => `${t._id} (${t.templateType})`).join(', ')}. Use the id.`);
  }
  return call(client, 'GET', `/v2/contenttemplate/${res.data[0]._id}`);
}

function templateSummary(t) {
  const pages = Array.isArray(t.pages) ? t.pages.length : 0;
  return {
    ...templateRow(t),
    pages,
    hasDesign: Boolean(t.html && String(t.html).trim()),
    images: Array.isArray(t.assets) ? t.assets.length : 0,
    defaultFont: t.defaultFont || null,
    secondaryFont: t.secondaryFont || null,
    embeddedFonts: t.embeddedFonts || [],
    metaPixelId: t.retargeting && t.retargeting.metaPixelId ? t.retargeting.metaPixelId : null,
    defaultLayout: t.defaultLayout && t.defaultLayout.origin ? t.defaultLayout : null,
    publishedInLibrary: Boolean(t.library && t.library.publish),
  };
}

// Where a template is used, and what a change to it reaches (verified against the renderer).
async function templateUsage(client, t) {
  const id = String(t._id);
  const out = { uses: {}, reach: [] };
  const add = async (key, object, xquery, select, label) => {
    const r = await countWhere(client, object, xquery, select);
    out.uses[key] = { count: r.count, ...(r.note ? { note: r.note } : {}), sample: (r.sample || []).map(label) };
  };
  if (t.templateType === 'layout') {
    await add('deals', 'deal', { 'proposal.template.layout': id }, 'dealName', (d) => ({ id: d._id, name: d.dealName }));
    await add('presentations', 'presentation', { layout: id }, 'title expirationDate', (p) => ({ id: p._id, title: p.title }));
    await add('messageTemplates', 'messagetemplate', { 'presentation.layout': id }, 'templateName', (m) => ({ id: m._id, name: m.templateName }));
    await add('emailCampaigns', 'emailcampaign', { 'presentation.layout': id }, 'emailCampaignName', (c) => ({ id: c._id, name: c.emailCampaignName }));
    await add('proposalWizards', 'proposalwizard', { 'proposalPreset.layout': id }, 'proposalWizardName', (w) => ({ id: w._id, name: w.proposalWizardName }));
    out.reach.push(
      'Each deal keeps its own copy of the layout design from the moment the layout was picked: a new design in the editor does not reach existing proposals until someone picks the layout again on the deal.',
      'Fonts, language, the agent card and other editor switches, the template script and the Meta pixel are read live from the layout on every view: changing them here changes every proposal and presentation above at once, including ones already sent.',
      'Presentations, campaign landings and proposal wizards use the layout live.',
    );
    if (t.defaultLayout && t.defaultLayout.origin) {
      out.reach.push(`It is the default layout (${t.defaultLayout.origin}): new proposals of the users it covers start with it.`);
    }
  } else if (t.templateType === 'snippet') {
    await add('products', 'product', { snippets: id }, 'productName productCode', (p) => ({ id: p._id, name: p.productName, code: p.productCode }));
    await add('productFamilies', 'productfamily', { snippets: id }, 'productFamilyName', (f) => ({ id: f._id, name: f.productFamilyName }));
    await add('productGroups', 'productgroup', { snippets: id }, 'productGroupName', (g) => ({ id: g._id, name: g.productGroupName }));
    out.reach.push('A snippet is read live on every view: any change shows at once on every proposal whose quote has a product, family or group that carries it, including proposals already sent.');
  } else if (t.templateType === 'content') {
    out.reach.push('Content is copied into the proposal when someone inserts it: changing the template does not change proposals that already have it.');
  } else {
    out.reach.push('No proposal, product or presentation points to this type of template.');
  }
  return out;
}

