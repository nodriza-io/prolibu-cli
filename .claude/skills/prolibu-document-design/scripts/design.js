const USAGE = `Usage: design.js <command> <domain> … [--profile <name>]
  templates <domain> [name] [--type layout|content|snippet|certificate|customView]
  show <domain> <template id|code>          design summary, where it is used, what a change reaches
  default-layout <domain>                   the layout new proposals of this key's user start with
  fonts <domain> [name]      views <domain>      plugins <domain>      system-templates <domain>
  presentations <domain> [title] [--contact <e-mail|id>]
  presentation <domain> <id|code>           views (who, when, how long), expiry
  preview <domain> '<plan json>'            writes nothing; returns a version
  apply <domain> '<plan json>' --version <v> --confirmed`;

function parseCli(argv) {
  const positional = [];
  const flags = {};
  const valued = ['version', 'profile', 'type', 'contact'];
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--confirmed') flags.confirmed = true;
    else if (arg.startsWith('--') && valued.includes(arg.slice(2))) {
      if (i + 1 >= argv.length) throw new UsageError(`Missing value for ${arg}.`);
      i += 1;
      flags[arg.slice(2)] = argv[i];
    } else if (arg.startsWith('--')) throw new UsageError(`Unknown option ${arg}.`);
    else positional.push(arg);
  }
  if (flags.type !== undefined && !TYPES.includes(flags.type)) throw new UsageError(`--type must be one of ${TYPES.join(', ')}.`);
  return { command: positional[0], domain: positional[1], rest: positional.slice(2), flags };
}

const COMMANDS = {
  templates: cmdTemplates,
  show: cmdShow,
  'default-layout': cmdDefaultLayout,
  fonts: cmdFonts,
  views: cmdViews,
  plugins: cmdPlugins,
  'system-templates': cmdSystemTemplates,
  presentations: cmdPresentations,
  presentation: cmdPresentation,
  preview: cmdPreview,
  apply: cmdApply,
};

// A 403 is final: the profile's user may not do this. Say so plainly so nobody retries it
// another way or with another profile.
const FORBIDDEN_HINT = 'The user of this profile does not have permission for this (403). The script stopped at '
  + 'this request: it did not retry it or try another profile. Tell the user; an admin can grant the permission.';

async function main(argv, opts = {}) {
  const rootDir = opts.rootDir || DEFAULT_ROOT;
  const stdout = opts.stdout || process.stdout;
  const stderr = opts.stderr || process.stderr;
  let client;
  const hide = (text) => (client ? client.redact(text) : String(text));
  try {
    const { command, domain, rest, flags } = parseCli(argv);
    const handler = COMMANDS[command];
    if (!handler || !domain) throw new UsageError(USAGE);
    client = createClient({ domain, rootDir, profile: flags.profile, fetchImpl: opts.fetchImpl, stderr });
    const ctx = { rootDir, stderr, apiFetch: opts.fetchImpl || globalThis.fetch };
    const result = await handler(client, rest, flags, ctx);
    stdout.write(`${hide(JSON.stringify(result, null, 2))}\n`);
    if (command === 'apply' && !result.saved) return 1;
    return result.blockers && result.blockers.length ? BLOCKED : 0;
  } catch (err) {
    if (err instanceof UsageError) {
      stderr.write(`${hide(err.message)}\n`);
      return 2;
    }
    if (err instanceof Blocked) {
      stderr.write(`BLOCKED: ${hide(err.message)}\n`);
      return BLOCKED;
    }
    if (err && err.status === 403) {
      stderr.write(`FORBIDDEN: ${hide(err.message)}\n${FORBIDDEN_HINT}\n`);
      return 1;
    }
    stderr.write(`Request failed: ${hide(err && err.message)}\n`);
    return 1;
  }
}

if (require.main === module) {
  main(process.argv.slice(2)).then((code) => { process.exitCode = code; });
}

